// Reads out/snapshot.json and writes:
//   out/import.sql      idempotent upserts for D1 (assets, public_items, asset_search)
//   out/sql/*.sql       the same statements split into smaller files for `wrangler d1 execute --file`
//   out/r2-plan.json    the R2 copy plan [{ sourceUrl, r2Key, contentType, ... }]
//
// Usage: tsx scripts/posewear/emit-sql.ts [--include-mature] [--category pose,outfit] [--chunk 400]
//
// Mature items (D-005) are skipped by default: public_items has no `mature`
// column yet, and the public library is a public surface.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  poseDepthR2Key,
  toLibraryD1Rows,
  type LibraryD1Rows,
  type PublicLibraryItem,
} from '../../packages/core/src/library/index.ts';
import { OUT_DIR, SNAPSHOT_PATH, parseArgs, readJson } from './lib.ts';

const args = parseArgs(process.argv.slice(2));
const includeMature = args.has('include-mature');
const categoryFilter = typeof args.get('category') === 'string' ? new Set(String(args.get('category')).split(',')) : undefined;
const CHUNK = Number(args.get('chunk') ?? 400);
const ROWS_PER_STATEMENT = 40;

/** SQLite literal. Strings are single-quoted with quotes doubled; no other escaping exists in SQLite. */
export function sqlLiteral(value: string | number | null | undefined): string {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`Non-finite number in SQL: ${value}`);
    return String(value);
  }
  return `'${value.replace(/\u0000/g, '').replace(/'/g, "''")}'`;
}

function insertStatements<T extends object>(
  table: string,
  rows: T[],
  conflict: string,
): string[] {
  if (!rows.length) return [];
  const columns = Object.keys(rows[0]!) as Array<keyof T>;
  const out: string[] = [];
  for (let i = 0; i < rows.length; i += ROWS_PER_STATEMENT) {
    const values = rows
      .slice(i, i + ROWS_PER_STATEMENT)
      .map((row) => `(${columns.map((c) => sqlLiteral(row[c] as string | number | null)).join(', ')})`)
      .join(',\n  ');
    out.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES\n  ${values}\n${conflict};`);
  }
  return out;
}

const upsert = (cols: string[]) =>
  `ON CONFLICT(id) DO UPDATE SET ${cols.map((c) => `${c} = excluded.${c}`).join(', ')}`;

function statementsFor(batch: LibraryD1Rows[]): string[] {
  const assets = batch.flatMap((b) => b.assets);
  const items = batch.map((b) => b.publicItem);
  const search = batch.map((b) => b.search);
  return [
    ...insertStatements('assets', assets, upsert(['kind', 'source', 'name', 'r2_key', 'meta', 'license'])),
    ...insertStatements(
      'public_items',
      items,
      upsert(['category', 'sub', 'title', 'prompt_en', 'prompt_zh', 'angles', 'asset_id', 'license', 'source']),
    ),
    // FTS5 tables have no unique key: delete then insert keeps re-runs idempotent.
    `DELETE FROM asset_search WHERE id IN (${search.map((s) => sqlLiteral(s.id)).join(', ')});`,
    ...insertStatements('asset_search', search, ''),
  ];
}

function contentTypeFor(key: string): string {
  if (key.endsWith('.png')) return 'image/png';
  if (key.endsWith('.jpg')) return 'image/jpeg';
  return 'image/webp';
}

function main(): void {
  const snapshot = readJson<{ fetchedAt: string; items: PublicLibraryItem[] }>(SNAPSHOT_PATH);
  const importedAt = Date.parse(snapshot.fetchedAt) || Date.now();
  const selected = snapshot.items.filter(
    (i) => (!categoryFilter || categoryFilter.has(i.category)) && (includeMature || !i.mature),
  );
  const rows = selected.map((item) => toLibraryD1Rows(item, { importedAt, depthR2KeyFor: poseDepthR2Key }));

  const header = [
    '-- PoseWear public library import (generated by scripts/posewear/emit-sql.ts).',
    `-- Snapshot: ${snapshot.fetchedAt}. Items: ${selected.length}. Mature included: ${includeMature}.`,
    '-- Idempotent: upserts on id; asset_search rows are replaced.',
    '-- Requires public_items.license to accept first-party (see D-004).',
    '',
  ].join('\n');

  const all: string[] = [];
  const chunkDir = join(OUT_DIR, 'sql');
  rmSync(chunkDir, { recursive: true, force: true });
  mkdirSync(chunkDir, { recursive: true });
  let fileIndex = 0;
  for (let i = 0; i < rows.length; i += CHUNK) {
    const statements = statementsFor(rows.slice(i, i + CHUNK));
    all.push(...statements);
    fileIndex++;
    writeFileSync(join(chunkDir, `import-${String(fileIndex).padStart(4, '0')}.sql`), `${header}${statements.join('\n\n')}\n`);
  }
  writeFileSync(join(OUT_DIR, 'import.sql'), `${header}${all.join('\n\n')}\n`);

  const plan = selected.flatMap((item) =>
    item.angles.map((angle) => ({
      sourceUrl: angle.fullUrl,
      r2Key: angle.r2Key,
      contentType: contentTypeFor(angle.r2Key),
      itemId: item.id,
      category: item.category,
      mature: item.mature,
    })),
  );
  writeFileSync(join(OUT_DIR, 'r2-plan.json'), JSON.stringify(plan, null, 1));

  const byCategory: Record<string, { items: number; objects: number }> = {};
  for (const item of selected) {
    const c = (byCategory[item.category] ??= { items: 0, objects: 0 });
    c.items++;
    c.objects += item.angles.length;
  }
  console.table(byCategory);
  console.log(
    `Wrote out/import.sql (${all.length} statements, ${fileIndex} chunk files in out/sql/) and out/r2-plan.json (${plan.length} objects). ` +
      `Skipped ${snapshot.items.length - selected.length} items (mature or filtered).`,
  );
}

main();
