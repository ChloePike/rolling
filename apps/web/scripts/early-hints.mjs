#!/usr/bin/env node
/**
 * Last build step: adds `Link` preloads for the app shell to `dist/_headers` (Workers static
 * assets), which Cloudflare turns into 103 Early Hints when the zone setting is on. The entry
 * script, stylesheet and preloaded font come from the built index.html, so names stay in step
 * with each build.
 *
 * The rule is `/*` (SPA routes are served index.html under their own URL); every other built
 * file and folder, and the prerendered legal pages (no app bundle), detach it with `! Link`.
 * The R2-served path derives the same header per HTML file (apps/api/src/lib/r2Static.ts:
 * `preloadLinks`; keep the patterns in step).
 */
import { appendFileSync, existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = process.argv[2] ? resolve(process.argv[2]) : fileURLToPath(new URL('../dist', import.meta.url));
const indexPath = join(dist, 'index.html');
if (!existsSync(indexPath)) throw new Error(`${indexPath} not found: run vite build first`);

const html = readFileSync(indexPath, 'utf8');
const head = html.slice(0, Math.max(0, html.indexOf('</head>')) || html.length);
const links = [];
for (const m of head.matchAll(/<script\b[^>]*\btype="module"[^>]*\bsrc="(\/assets\/[^"]+\.js)"/g)) links.push(`<${m[1]}>; rel=modulepreload; crossorigin`);
for (const m of head.matchAll(/<link\b[^>]*\brel="stylesheet"[^>]*\bhref="(\/assets\/[^"]+\.css)"/g)) links.push(`<${m[1]}>; rel=preload; as=style; crossorigin`);
for (const m of head.matchAll(/<link\b[^>]*\brel="preload"[^>]*\bhref="(\/assets\/[^"]+\.woff2)"/g)) links.push(`<${m[1]}>; rel=preload; as=font; type="font/woff2"; crossorigin`);
if (links.length === 0) {
  console.log('early-hints: no preloads found in index.html');
  process.exit(0);
}

const detach = [];
for (const name of readdirSync(dist).sort()) {
  if (name === 'index.html' || name === '_headers' || name === '_redirects') continue;
  if (statSync(join(dist, name)).isDirectory()) detach.push(`/${name}/*`);
  else {
    detach.push(`/${name}`);
    if (name.endsWith('.html')) detach.push(`/${name.slice(0, -5)}`);
  }
}

const block = [
  '',
  '# Early Hints for the app shell (generated by scripts/early-hints.mjs).',
  '/*',
  `  Link: ${[...new Set(links)].join(', ')}`,
  ...detach.flatMap((p) => [p, '  ! Link']),
  '',
].join('\n');
appendFileSync(join(dist, '_headers'), block);
console.log(`early-hints: ${links.length} preloads, ${detach.length} paths without them`);
