#!/usr/bin/env node
/**
 * Writes `src/email/catalog.gen.ts` from `messages/<locale>/email.json` (D-023): the Worker
 * bundle cannot glob the messages folder, so the email strings of every locale are inlined.
 * Run after adding or changing an email translation:
 *   node packages/core/scripts/gen-email-catalog.mjs          (write)
 *   node packages/core/scripts/gen-email-catalog.mjs --check  (exit 1 when stale)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const messagesDir = join(here, '../../../messages');
const out = join(here, '../src/email/catalog.gen.ts');

export function buildCatalogSource() {
  const locales = readdirSync(messagesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(messagesDir, d.name, 'email.json')))
    .map((d) => d.name)
    .sort((a, b) => (a === 'en' ? -1 : b === 'en' ? 1 : a.localeCompare(b)));
  const en = JSON.parse(readFileSync(join(messagesDir, 'en', 'email.json'), 'utf8'));
  const catalog = {};
  for (const locale of locales) {
    const raw = JSON.parse(readFileSync(join(messagesDir, locale, 'email.json'), 'utf8'));
    // Only keys English has, non-empty: missing ones fall back to English when rendering.
    catalog[locale] = Object.fromEntries(Object.keys(en).filter((k) => typeof raw[k] === 'string' && raw[k] !== '').map((k) => [k, raw[k]]));
  }
  return [
    '// Generated by packages/core/scripts/gen-email-catalog.mjs from messages/<locale>/email.json. Do not edit.',
    'export const EMAIL_CATALOG: Record<string, Record<string, string>> = ' + JSON.stringify(catalog, null, 2) + ';',
    '',
  ].join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const source = buildCatalogSource();
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== source) {
      console.error('packages/core/src/email/catalog.gen.ts is stale: run node packages/core/scripts/gen-email-catalog.mjs');
      process.exit(1);
    }
  } else if (current !== source) {
    writeFileSync(out, source);
    console.log('Wrote packages/core/src/email/catalog.gen.ts');
  }
}
